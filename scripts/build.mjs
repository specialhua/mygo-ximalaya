import { build } from "esbuild";
import { readFile } from "node:fs/promises";

const pkg = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const manifest = JSON.parse(await readFile(new URL("../plugin.json", import.meta.url), "utf8"));
if (pkg.version !== manifest.version) throw new Error("package.json and plugin.json versions differ");
await build({
  entryPoints: [new URL("../src/index.js", import.meta.url).pathname],
  outfile: new URL("../index.js", import.meta.url).pathname,
  bundle: true, format: "esm", platform: "neutral", target: "es2020",
  legalComments: "inline", charset: "utf8", treeShaking: true,
  banner: { js: "// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by npm run build. Edit src/, not this file.\n// Bundled dependency notices: THIRD_PARTY_NOTICES.md" },
});
